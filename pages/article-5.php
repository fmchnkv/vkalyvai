                    <h1 class="article__title">Правила модерации вакансий: как избежать блокировок со стороны ФАС и Минтруда</h1>
                    <div class="article__content content">
                        <p>При найме линейного персонала у каждого руководителя или HR-менеджера есть четкий образ идеального кандидата. Например, на склад часто ищут «крепких мужчин до 35 лет», а на позицию кассира — «приветливых девушек».</p>
                        <p>Однако если вы напишете эти требования прямо в тексте вакансии, ваше объявление будет моментально заблокировано модераторами <b>ВКАЛЫВАй</b>, а компания рискует получить крупный штраф от Федеральной антимонопольной службы (ФАС) или Минтруда РФ.</p>
                        <p>В этой инструкции мы разберем требования статьи 3 Трудового кодекса РФ и закона «О занятости населения», регламентирующие запрет на дискриминацию, и научим вас составлять описания вакансий так, чтобы они одобрялись модераторами с первого раза.</p>
                        <p id="s-1"><b>Что закон считает дискриминацией?</b></p>
                        <p>Согласно российскому законодательству, в тексте вакансии категорически запрещено указывать любые прямые или косвенные ограничения, которые не связаны с деловыми качествами работника. К ним относятся:</p>
                        <ul>
                            <li><b>Пол</b> (нельзя писать: «требуется мужчина», «вакансия для женщин»);</li>
                            <li><b>Возраст</b> (запрещены любые рамки: «от 21 года», «до 45 лет», «молодой коллектив»);</li>
                            <li><b>Национальность и гражданство</b> (нельзя указывать: «только славяне», «только с гражданством РФ»);</li>
                            <li><b>Место жительства</b> (запрещено требовать: «строго с местной пропиской»);</li>
                            <li><b>Другие личные качества</b> (семейное положение, наличие детей, внешность, отсутствие вредных привычек).</li>
                        </ul>
                        <p>Любое из этих требований в открытом тексте — это прямое нарушение закона, за которое предусмотрены административные штрафы (ст. 13.11.1 КоАП РФ).</p>
                        <p id="s-2"><b>Как обойти скрытые ловушки: переводим личные требования на язык деловых качеств</b></p>
                        <p>Чтобы ваша вакансия успешно прошла модерацию и привлекла нужных людей, все физические или демографические требования необходимо перевести в плоскость <b>профессиональных обязанностей и условий труда</b>.</p>
                        <p id="s-3"><b>Ловушка 1: Пол (Ищете мужчин на тяжелую работу)</b></p>
                        <ul>
                            <li><b>Как писать нельзя</b>: «Требуются мужчины-грузчики на склад цемента».</li>
                            <li><b>Как написать правильно</b>: «Вакансия: Грузчик. Обязанности: Разгрузка и перемещение мешков весом до 50 кг. Работа требует высокой физической выносливости. Предоставляется теплая спецодежда».</li>
                            <li><i>Почему это пропустит модератор</i>: Вы не ограничили права женщин юридически, но честно описали условия труда и тяжесть груза. Кандидаты сами оценят свои силы.</li>
                        </ul>
                        <p id="s-4"><b>Ловушка 2: Возраст (Ищете молодых и активных курьеров)</b></p>
                        <ul>
                            <li><b>Как писать нельзя</b>: «Ищем активных парней и девушек от 18 до 25 лет для доставки еды».</li>
                            <li><b>Как написать правильно</b>: «Вакансия: Курьер по доставке заказов. Условия: Динамичная работа на ногах, пеший маршрут до 10-12 км в день. Требуется уверенное владение смартфоном и навигационными приложениями».</li>
                            <li><i>Почему это пропустит модератор</i>: Смартфон и скорость движения — это профессиональные требования и навыки, а не возрастные рамки.</li>
                        </ul>
                        <p id="s-5"><b>Ловушка 3: Гражданство и документы (Нужны только местные сотрудники)</b></p>
                        <ul>
                            <li><b>Как писать нельзя</b>: «Принимаем только граждан РФ, славянской внешности».</li>
                            <li><b>Как написать правильно</b>: «Вакансия: Комплектовщик. Обязанности: Работа со складской документацией и маркировками на русском языке. Требуется полный пакет документов для официального трудоустройства в соответствии с законодательством РФ».</li>
                            <li><i>Почему это пропустит модератор</i>: Знание языка и наличие документов для оформления по ТК РФ — это законное требование любого бизнеса.</li>
                        </ul>
                        <p><b>Важный лайфхак для платформы ВКАЛЫВАй</b>: Чтобы отсечь кандидатов без документов, не пишите об этом в тексте. При создании вакансии просто отметьте нужные галочки в интерактивном блоке «Разрешение на работу / Документы». Наша система сама скроет вакансию от тех, у кого в резюме указаны неподходящие параметры, и вам не придется нарушать закон.</p>
                        <p id="s-6"><b>Что делать, если вакансию все-таки отклонили?</b></p>
                        <p>Если модератор приостановил публикацию, вам в личный кабинет придет уведомление с точным указанием проблемной фразы (например: «Удалите ограничение по возрасту в блоке Требования»).</p>
                        <p>Просто нажмите кнопку <b>«Редактировать»</b>, замените спорное предложение на описание профессиональных навыков и сохраните изменения. Вакансия автоматически уйдет на повторную быструю проверку и появится в поиске соискателей в течение нескольких минут.</p>
                        <p>Пишите описания профессионально, нанимайте команду законно и вкалывайте эффективно вместе с <b>ВКАЛЫВАй</b>!</p>
