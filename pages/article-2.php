                        <p>Наш портал — это пространство для делового и уважительного общения. Любые ругательства, оскорбления в адрес прошлых работодателей или агрессивные требования в тексте приведут к вечной блокировке аккаунта.</p>
                        <p>То же самое касается фотографий: не загружайте на аватар снимки в темных очках, фотографии из паспорта с личными данными, чужие картинки из интернета или фото с дружеских застолий. Поставьте простое, четкое селфи с нейтральным лицом.</p>
                        <p id="error-5"><b>Ошибка 5. Ложные данные о гражданстве и документах</b></p>
                        <p>Для линейного персонала (особенно в логистике и ритейле) юридическая чистота документов — это вопрос номер один. Не отмечайте галочку «Гражданство РФ», если у вас другой паспорт, в надежде «договориться на месте». Работодатель все равно увидит документы при оформлении, а ваш профиль на сайте получит жалобу от компании и будет заблокирован. Будьте честны — на сайте тысячи вакансий для иностранных граждан с патентами и документами ЕАЭС.</p>
