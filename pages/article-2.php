                            <li><b>Как сделать правильно</b>: Напишите честно, даже если ваш опыт скромный. Если вы ищете работу грузчиком, так и напишите: «Разгрузка фур, перемещение товара по складу, работа в паре с водителем».</li>
                        </ul>
                        <p id="error-2"><b>Ошибка 2. Текст, написанный с помощью CAPS LOCK</b></p>
                        <p>Текст, состоящий целиком из заглавных букв, выглядит как крик и визуально ломает дизайн сайта. Такие анкеты автоматически отклоняются системой.</p>
                        <ul>
                            <li><b>Как делать нельзя</b>: «ИЩУ РАБОТУ ВОДИТЕЛЕМ СРОЧНО ВЫПЛАТЫ КАЖДЫй ДЕНЬ».</li>
                            <li><b>Как сделать правильно</b>: Пишите стандартным шрифтом, используя заглавные буквы только в начале предложений и в аббревиатурах: «Водитель на авто компании (ГАЗель). Срочно ищу работу с ежедневными выплатами».</li>
                        </ul>
                        <p id="error-3"><b>Ошибка 3. Контакты и ссылки в неположенных местах</b></p>
