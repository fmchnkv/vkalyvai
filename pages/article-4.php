                        <p>В этой короткой инструкции мы расскажем, как эта система работает и как она экономит HR-менеджерам до 10 часов рабочего времени в неделю.</p>
                        <p id="s-1"><b>Что такое умный мэтчинг на ВКАЛЫВАй?</b></p>
                        <p><b>Мэтчинг</b> (от английского match — совпадение) — это интеллектуальный алгоритм, который в режиме реального времени сравнивает требования вашей вакансии с анкетами соискателей в нашей базе.</p>
                        <p>Система не просто ищет совпадения по названию должности. Она анализирует глубокие параметры:</p>
                        <ul>
                            <li>Наличие специфических навыков (например, работа с терминалом ТСД или знание 1С:WMS);</li>
                            <li>Желаемый график работы и формат оплаты (за смену, за месяц, вахта);</li>
                            <li>Категории водительских прав и наличие личного автомобиля;</li>
                            <li>Юридические документы (гражданство, наличие патента или медкнижки).</li>
                        </ul>
                        <p id="s-2"><b>Как это выглядит на практике?</b></p>
                        <p>Вам больше не нужно открывать каждое резюме по очереди и сверять строчки. Система делает это автоматически и выводит результат прямо в интерфейсе:</p>
                        <ol>
                            <li><b>Процент соответствия на карточке</b>: В общей ленте выдачи на каждой карточке кандидата вы увидите четкий оранжевый индикатор (например: «Подходит вам на 85%»).</li>
                            <li><b>Подсказка для HR</b>: Алгоритм выведет короткую текстовую строчку, объясняющую оценку. Например: «У кандидата совпадают 4 ключевых навыка из 5, есть права категории С и опыт работы на ричтраке».</li>
                            <li><b>Автоматическая сортировка</b>: По умолчанию в фильтре «Сортировка» стоит режим «По активности и мэтчингу». Это значит, что первыми в списке вы всегда будете видеть людей, которые идеально подходят под ваши требования и обновляли анкету за последние 24 часа.</li>
                        </ol>
