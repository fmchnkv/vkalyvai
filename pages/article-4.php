                            <li><b>Не пишите требования «стеной текста» в описании</b>. Наш робот считывает параметры из специальных интерактивных блоков-чекбоксов.</li>
                            <li><b>Четко заполняйте блоки параметров</b>. Если для работы кладовщика критически важно умение собирать заказы по сканеру ТСД — обязательно отметьте этот навык галочкой при публикации.</li>
                        </ul>
